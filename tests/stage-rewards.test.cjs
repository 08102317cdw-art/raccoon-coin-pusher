const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const load = file => import('data:text/javascript;base64,' + Buffer.from(fs.readFileSync(file)).toString('base64'));
  const rewards = await load('src/stage-rewards.js');
  const { Run, UPGRADES } = await load('src/roguelike.js');
  const { TokenSystem } = await load('src/tokens.js');
  const { spinLottery, rollPicks, applyPick, rerollPicks, LOTTERY, PRIZES, ENERGY_GOAL } = rewards;
  let checks = 0;
  const check = (truth, label) => { assert.ok(truth, label); checks++; };
  check(ENERGY_GOAL === 8 && PRIZES.shell && PRIZES.chest && PRIZES.plushie, 'energy goal and three prize kinds');
  const seq = [0, 0.1, 0.2, 0.3, 0.4, 0.99];
  let i = 0;
  const random = () => seq[i++ % seq.length];
  const seen = new Set();
  for (let n = 0; n < 40; n++) seen.add(spinLottery(() => n / 40).id);
  check([...seen].every(id => LOTTERY.some(item => item.id === id)) && seen.size >= 4, 'lottery stays inside the published wheel');
  const run = new Run(null, random);
  for (let n = 0; n < 7; n++) run.award('coin');
  check(run.energy === 0 && run.pendingSpin === 0, 'banked scores no longer charge a separate wheel');
  run.award('coin');
  check(run.energy === 0 && run.pendingSpin === 0, 'the eighth banked score does not auto-spin');
  const picks = rollPicks(run, { random: () => 0.1, coinIds: ['seed', 'cat', 'bomb'], upgrades: UPGRADES, names: { seed: '种子币', cat: '猫猫币', bomb: '爆破币' } });
  check(picks.length === 3 && new Set(picks.map(card => card.kind + card.id)).size === 3, 'draft offers three different cards');
  check(picks.every(card => ['common', 'uncommon', 'rare'].includes(card.rarity)), 'cards carry a rarity');
  const relic = { kind: 'relic', id: 'tide', name: '潮汐芯', max: 3 };
  check(applyPick(run, relic) && run.relics.tide === 1 && !applyPick(run, relic), 'one draft choice sticks');
  run.picked = false; run.pickRerolls = 1; run.picks = picks;
  check(rerollPicks(run, { random: () => 0.2, coinIds: ['seed'], upgrades: UPGRADES, names: { seed: '种子币' } }) && run.pickRerolls === 0 && !rerollPicks(run), 'one reroll then locked');
  const kit = new TokenSystem();
  check(kit.select('seed') && kit.clip.includes('seed') && kit.clipSize === 2, 'selecting a special fills a coin slot');
  kit.setClipSize(3);
  check(kit.clipSize === 3, 'clip expansion adds a slot');
  const old = new TokenSystem({ bag: { seed: 1 }, selected: 'seed' });
  check(old.clip[0] === 'seed' && old.clipSize === 2, 'older saves arm the selected coin into a slot');
  const saved = new Run(JSON.parse(JSON.stringify(run.serialize())));
  check(saved.energy === run.energy && saved.relics.tide === 1 && saved.pendingSpin === run.pendingSpin, 'energy and relics survive a reload');
  console.log(`PASS: ${checks} stage-reward assertions`);
})().catch(e => { console.error(e); process.exitCode = 1; });