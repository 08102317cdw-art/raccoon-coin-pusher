const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const { Run, TARGETS, UPGRADES } = await import('data:text/javascript;base64,' + Buffer.from(fs.readFileSync('src/roguelike.js')).toString('base64'));
  let checks = 0;
  const check = (truth, label) => { assert.ok(truth, label); checks++; };
  const run = new Run(null, () => 0.5);
  check(run.shots === 50 && run.target === 300 && run.multiplier === 1, 'fresh run');
  check(run.award('coin').points === 10, 'normal coin');
  run.levels.mult = 2; run.levels.value = 1;
  check(run.award('coin', 5, true).points === 54, 'base 12 × 1.5 × 1.5 × 2');
  check(run.award('gem', 100).points === 450, 'combo cap');
  check(run.award('missing') === null, 'invalid coin ignored');
  const shots = run.shots;
  run.award('plush'); check(run.shots === shots, 'wins do not refund shots');
  check(run.finish() && run.phase === 'shop', 'clear enters shop');
  const cash = run.cash; check(cash > 0, 'reward given');
  check(!run.finish() && run.cash === cash, 'settlement idempotent');
  check(!run.spendShot() && !run.award('coin'), 'no scoring or dropping in shop');
  run.offers = ['mult', 'reserve', 'supply']; run.cash = 100;
  check(run.buy('mult') && run.level('mult') === 3, 'upgrade purchase');
  check(!run.buy('mult'), 'duplicate purchase blocked');
  check(run.buy('reserve') && run.buy('supply'), 'supply and capacity');
  const serialized = run.serialize(); const restored = new Run(serialized);
  check(JSON.stringify(serialized) === JSON.stringify(restored.serialize()), 'shop save roundtrip');
  check(restored.next() && restored.round === 2 && restored.score === 0 && restored.shots === 70, 'next stage applies upgrades and supply');
  check(restored.total > 0 && restored.level('mult') === 3, 'total and upgrades retained');
  check(restored.pendingShots === 0 && !restored.next(), 'next is idempotent');
  for (let i=0;i<70;i++) check(restored.spendShot(), 'limited shot '+i);
  check(restored.phase === 'settling' && !restored.spendShot(), 'empty budget enters settling');
  check(!restored.tick(20,true) && restored.settle === 3, 'pending slot extends settling');
  check(restored.tick(4,false) && restored.phase === 'gameover', 'failed run ends after grace');
  check(restored.cash === serialized.cash, 'failed run gives no reward');
  const reroll = new Run(); reroll.score = 300; reroll.finish(); reroll.cash = 3;
  check(reroll.reroll() && reroll.cash === 0 && !reroll.reroll(), 'one reroll and currency accounting');
  const broke = new Run(); broke.score=300; broke.finish(); broke.cash=0; broke.offers=['mult'];
  check(!broke.buy('mult') && broke.level('mult')===0, 'insufficient funds blocked');
  const max = new Run(); max.score=300; max.finish(); max.cash=10000;
  for(const [id,u] of Object.entries(UPGRADES)) if(id!=='supply') max.levels[id]=u.max;
  max.rollOffers(); check(max.offers.every(id=>id==='supply'), 'max upgrades excluded');
  check(!max.buy('mult'), 'unoffered item blocked');
  const complete = new Run();
  for(let round=1;round<=8;round++) { complete.score=complete.target; check(complete.finish(), 'clear stage '+round); if(round<8) check(complete.next(), 'advance '+round); }
  check(complete.phase==='victory' && !complete.next() && complete.round===8, 'finite victory');
  check(new Run(complete.serialize()).phase==='victory', 'victory persists');
  const threshold = new Run(); threshold.score=299; threshold.shots=1; threshold.spendShot(); threshold.award('coin'); threshold.tick(16);
  check(threshold.phase==='shop', 'last coin can clear stage');
  const remaining = new Run(); remaining.score=300; remaining.finish();
  check(remaining.receipt.thrift===6 && remaining.receipt.reward===16, 'remaining shot reward capped');
  check(TARGETS.every((n,i)=>!i||n>TARGETS[i-1]), 'targets increase');
  const exchange = new Run(); exchange.tickets = 40;
  check(exchange.exchange() && exchange.shots === 58 && exchange.tickets === 28 && exchange.exchanged === 1, 'first exchange buys eight shots');
  check(exchange.exchange() && exchange.shots === 66 && exchange.tickets === 10 && !exchange.exchange(), 'second exchange costs more and a third is blocked');
  const resume = new Run(); resume.shots = 0; resume.phase = 'settling'; resume.settle = 4; resume.tickets = 20;
  check(resume.exchange() && resume.phase === 'playing' && resume.shots === 8 && resume.settle === 0, 'exchange resumes a settling round');
  const shopExchange = new Run(); shopExchange.score = 300; shopExchange.finish(); shopExchange.tickets = 100;
  check(!shopExchange.exchange() && shopExchange.tickets === 100, 'shop blocks exchange');
  const brokeTickets = new Run(); brokeTickets.tickets = 11;
  check(!brokeTickets.exchange() && brokeTickets.shots === 50, 'exchange needs tickets');
  const table = new Run();
  check(table.shake() && table.shakes === 0 && !table.shake(), 'one free table shake per run');
  const shopShake = new Run(); shopShake.score = 300; shopShake.finish();
  check(!shopShake.shake() && shopShake.shakes === 1, 'shake waits until the machine is live');
  const pinned = new Run(); pinned.levels.pin = 1;
  for (let i = 0; i < 19; i++) check(!pinned.noteInsert(), 'pin waits for 20');
  check(pinned.noteInsert() && pinned.inserts === 20, 'pin shakes on the 20th insert');
  pinned.award('coin'); pinned.score = 300; pinned.finish(); pinned.shakes = 0; pinned.exchanged = 2; pinned.inserts = 20;
  check(pinned.next() && pinned.shakes === 0 && pinned.exchanged === 0 && pinned.inserts === 0, 'next round resets exchange and pin count only');
  check(pinned.tickets > 0, 'scoring tickets carry into the next round');
  assert.throws(()=>new Run({round:99,phase:'playing'})); checks++;
  assert.throws(()=>new Run({round:1,phase:'victory',score:300,receipt:{won:true}})); checks++;
  assert.throws(()=>new Run({round:1,phase:'shop',score:1,receipt:{won:false}})); checks++;
  console.log(`PASS: ${checks} run-rule assertions`);
})().catch(e=>{console.error(e);process.exitCode=1;});
