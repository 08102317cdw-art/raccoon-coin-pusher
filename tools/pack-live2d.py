"""Pack the checked-in, licensed model (no network) into the offline asset module."""
import base64, gzip, hashlib, json, mimetypes
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=root/'models/mascot-live2d'
assets={}; manifest=[]
for path in sorted(source.rglob('*')):
    if not path.is_file() or path.name=='MANIFEST.json' or path.suffix not in {'.json','.moc3','.png'}: continue
    name=path.relative_to(source).as_posix(); data=path.read_bytes()
    mime='application/json' if path.suffix=='.json' else mimetypes.guess_type(name)[0] or 'application/octet-stream'
    assets[name]={'mime':mime,'gzip':base64.b64encode(gzip.compress(data,mtime=0)).decode()}
    manifest.append({'path':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
(root/'src/art/live2d-assets.js').write_text('// Licensed Q肥鱼 model; see models/mascot-live2d/SOURCE.md. Generated by tools/pack-live2d.py.\nexport default '+json.dumps(assets,separators=(',',':'))+';\n')
(source/'MANIFEST.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print('Packed',len(assets),'local Live2D resources')
